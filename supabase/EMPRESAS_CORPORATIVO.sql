-- PARTE F — Scheduling con pg_cron (correr al final, con placeholders)
-- ══════════════════════════════════════════════════════════════════════════
--
-- Requisitos previos:
--   1. Deployá la Edge Function:
--        supabase functions deploy acreditar-creditos-corporativos --no-verify-jwt
--   2. Reutiliza el CRON_SECRET que ya usás para los otros crons (si no lo
--      seteaste todavía: supabase secrets set CRON_SECRET=algo-largo-y-secreto).
--   3. Reemplazá <PROJECT_REF>, <ANON_KEY> y <CRON_SECRET>.
--
-- pg_cron corre en UTC. Argentina es UTC-3 (sin DST): 00:00 ART = 03:00 UTC.
-- Día 1 de cada mes a las 00:00 ART  ->  '0 3 1 * *'.

create extension if not exists pg_cron;
create extension if not exists pg_net;

select cron.schedule(
  'acreditar-creditos-corporativos-mensual',
  '0 3 1 * *',
  $$
  select net.http_post(
    url     := 'https://<PROJECT_REF>.supabase.co/functions/v1/acreditar-creditos-corporativos',
    headers := jsonb_build_object(
      'Content-Type',   'application/json',
      'Authorization',  'Bearer <ANON_KEY>',
      'x-cron-secret',  '<CRON_SECRET>'
    ),
    body    := '{}'::jsonb
  );
  $$
);

