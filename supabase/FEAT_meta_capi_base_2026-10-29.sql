-- ── Registro de cada evento mandado (o a mandar) a Meta ────────────────────
create table if not exists public.meta_capi_eventos (
  id            bigint generated by default as identity primary key,
  event_id      text not null unique,
  event_name    text not null,
  usuario_id    uuid references public.usuarios (id) on delete set null,
  pago_id       uuid references public.pagos (id) on delete set null,
  status        text not null default 'pending'
                check (status in ('pending', 'delivered', 'failed', 'skipped')),
  attempts      integer not null default 0,
  meta_response jsonb,
  last_error    text,
  created_at    timestamptz not null default now(),
  updated_at    timestamptz not null default now(),
  delivered_at  timestamptz
);
create index if not exists meta_capi_eventos_usuario_created
  on public.meta_capi_eventos (usuario_id, created_at desc);
create index if not exists meta_capi_eventos_pago
  on public.meta_capi_eventos (pago_id) where pago_id is not null;
-- RLS prendido y SIN políticas: desde la app no se lee ni se escribe.
alter table public.meta_capi_eventos enable row level security;

