-- ── El token y el código de prueba en el Vault ─────────────────────────────
-- meta-capi-event los busca primero en los secrets de las Edge Functions y,
-- si no están, acá. Sólo el servidor puede llamar a estas dos funciones.
create or replace function public.get_meta_capi_config()
 returns jsonb
 language sql
 stable security definer
 set search_path to 'public', 'vault'
as $function$
  select jsonb_build_object(
    'access_token', max(decrypted_secret) filter (where name = 'META_CAPI_ACCESS_TOKEN'),
    'test_event_code', max(decrypted_secret) filter (where name = 'META_TEST_EVENT_CODE')
  )
  from vault.decrypted_secrets
  where name in ('META_CAPI_ACCESS_TOKEN', 'META_TEST_EVENT_CODE');
$function$;
revoke all on function public.get_meta_capi_config() from public, anon, authenticated;
grant execute on function public.get_meta_capi_config() to service_role;

create or replace function public.set_meta_capi_token(p_token text)
 returns void
 language plpgsql
 security definer
 set search_path to 'public', 'vault'
as $function$
declare
  v_id uuid;
begin
  if p_token is null or length(trim(p_token)) < 40 then
    raise exception 'Token inválido';
  end if;

  select id into v_id
  from vault.secrets
  where name = 'META_CAPI_ACCESS_TOKEN'
  limit 1;

  if v_id is null then
    perform vault.create_secret(trim(p_token), 'META_CAPI_ACCESS_TOKEN', 'Meta Conversions API');
  else
    perform vault.update_secret(v_id, trim(p_token), 'META_CAPI_ACCESS_TOKEN', 'Meta Conversions API');
  end if;
end;
$function$;
revoke all on function public.set_meta_capi_token(text) from public, anon, authenticated;
grant execute on function public.set_meta_capi_token(text) to service_role;

